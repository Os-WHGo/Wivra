package com.oswhgo.wivra

import android.content.Context
import android.net.Uri
import androidx.core.content.FileProvider
import org.json.JSONArray
import org.json.JSONObject
import java.io.File
import java.time.Instant

/**
 * Provide the existing editor with a completed, user-saved phone MP4/WAV
 * pair and a tiny valid manifest v2. Never copy or pass private media paths.
 * Neither pending clips nor another app's media may appear in this catalog.
 */
object WivraCaptureImport {
    data class Bundle(val title: String, val uris: Array<Uri>)

    @JvmStatic
    fun bundles(context: Context): List<Bundle> {
        val videos = WivraPhoneMediaStore.latestSavedVideos(context).associateBy { it.uri.toString() }
        val audio = WivraPhoneMediaStore.latestSavedWav(context).associateBy { it.uri.toString() }
        val privateDir = File(context.filesDir, "phone-pending")
        if (!privateDir.isDirectory || java.nio.file.Files.isSymbolicLink(privateDir.toPath())) return emptyList()
        val sidecars = privateDir.listFiles()?.filter {
            it.isFile && !java.nio.file.Files.isSymbolicLink(it.toPath()) &&
                it.canonicalFile.parentFile == privateDir.canonicalFile &&
                it.name.startsWith("pending-phone-") && it.name.endsWith(".wivra.json") &&
                it.length() in 1..32768
        }?.sortedByDescending { it.lastModified() } ?: return emptyList()
        val destinationDir = File(context.cacheDir, "wivra-capture-import")
        if (!destinationDir.isDirectory && !destinationDir.mkdirs()) return emptyList()
        if (java.nio.file.Files.isSymbolicLink(destinationDir.toPath())) return emptyList()
        val result = mutableListOf<Bundle>()
        for (sidecar in sidecars) {
            if (result.size == 12) break
            try {
                val raw = JSONObject(sidecar.readText())
                if (raw.optInt("schemaVersion") != 2 ||
                    raw.optString("audioStatus") != "ready" ||
                    raw.optString("timebase") != "elapsedRealtimeNanos") continue
                val video = videos[raw.optString("publishedVideoUri")] ?: continue
                val wav = audio[raw.optString("publishedAudioUri")] ?: continue
                if (!video.title.endsWith(".mp4", true) || !wav.title.endsWith(".wav", true) ||
                    video.title.dropLast(4) != wav.title.dropLast(4)) continue

                // App-private sidecar filenames were generated by createPrivateVideo.
                // Validate after canonicalization; do not use a provider-supplied filename.
                val stem = sidecar.name.removeSuffix(".wivra.json")
                val jsonFile = File(destinationDir, "$stem.wivra.json")
                if (jsonFile.canonicalFile.parentFile != destinationDir.canonicalFile) continue
                val rawOffset = raw.opt("audioStartOffsetSeconds")
                val offset = if (rawOffset is Number && rawOffset.toDouble().isFinite())
                    rawOffset else JSONObject.NULL
                val track = JSONObject().put("id", "audio-1").put("kind", "audio")
                    .put("role", "voice_primary").put("source", "android-phone-mic")
                    .put("file", wav.title).put("channelIndex", JSONObject.NULL)
                    .put("channelCount", 1).put("sampleRateHz", 48000)
                    .put("startOffsetSeconds", offset)
                val manifest = JSONObject()
                    .put("schemaVersion", 2)
                    .put("captureID", "android-phone:$stem")
                    .put("cameraSource", "android-phone-camerax")
                    .put("audioSource", "android-phone-mic")
                    .put("selectedInputName", JSONObject.NULL)
                    .put("originalVideoFile", video.title)
                    .put("originalAudioFile", wav.title)
                    .put("muxedVideoFile", JSONObject.NULL)
                    .put("createdAtISO8601", Instant.ofEpochMilli(sidecar.lastModified()).toString())
                    .put("tracks", JSONArray().put(track))
                    .put("muxedFromTrackIDs", JSONArray())
                // Cache only JSON; original audiovisual bytes stay in MediaStore.
                val tmp = File(destinationDir, "$stem.wivra.json.tmp")
                try {
                    tmp.writeText(manifest.toString(), Charsets.UTF_8)
                    if (!tmp.renameTo(jsonFile)) {
                        tmp.copyTo(jsonFile, overwrite = true)
                    }
                } finally { tmp.delete() }
                val manifestUri = FileProvider.getUriForFile(context,
                    context.packageName + ".captureimports", jsonFile)
                result.add(Bundle(video.title, arrayOf(manifestUri, video.uri, wav.uri)))
            } catch (_: Exception) {
                // Stale, revoked or invalid pairs are not advertised as available.
            }
        }
        return result
    }
}
